export const SIGNERS: Signer[] = NAMES.map((name) => ({
  name,
  slug: toSlug(name),
}));

export function getSignerBySlug(slug: string): Signer | undefined {
  const decoded = decodeURIComponent(slug);
  return SIGNERS.find((s) => s.slug === decoded || s.slug === slug);
}
